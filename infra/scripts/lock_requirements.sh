#!/usr/bin/env bash
# Regenerate requirements.lock: exact versions of everything requirements.txt pulls in,
# as resolved on the Lambda base image (linux/arm64, the deployed Python).
#
#   infra/scripts/lock_requirements.sh            fresh resolve: pip install -r requirements.txt
#                                                 in a throwaway base-image container (network)
#   infra/scripts/lock_requirements.sh <image>    no install: read what's in a built image,
#                                                 e.g. <ecr repo>:worker-<sha> (no network)
#
# The lock is a pip *constraints* file: the Dockerfile and requirements-dev.txt install
# requirements.txt with -c requirements.lock. Only the closure of requirements.txt is
# written, not the base image's own runtime packages (awslambdaric, ...), so the same file
# works on a laptop. Review the diff, rebuild, run the tests, commit both files together.
set -euo pipefail

BASE_IMAGE="public.ecr.aws/lambda/python:3.12"  # keep in step with the Dockerfile's FROM
image="${1:-}"
root="$(git rev-parse --show-toplevel)"
cd "$root"

# Walks requirements.txt through each installed distribution's metadata (extras and
# environment markers included) and prints name==version, sorted.
read -r -d '' CLOSURE <<'PY' || true
import sys
from importlib.metadata import distribution
from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name

def wanted(req, extras):
    return req.marker is None or any(req.marker.evaluate({"extra": e}) for e in extras or {""})

top = [Requirement(line.split("#", 1)[0].strip())
       for line in open(sys.argv[1]) if line.split("#", 1)[0].strip()]
todo, done, pins = [(r, set(r.extras)) for r in top if wanted(r, set())], set(), {}
while todo:
    req, extras = todo.pop()
    key = (canonicalize_name(req.name), frozenset(extras))
    if key in done:
        continue
    done.add(key)
    dist = distribution(req.name)
    pins[key[0]] = f"{dist.metadata['Name']}=={dist.version}"
    todo += [(d, set(d.extras)) for d in map(Requirement, dist.requires or []) if wanted(d, extras)]
print("\n".join(pins[k] for k in sorted(pins)))
PY

if [[ -n "$image" ]]; then
  source="image tag ${image##*:}"  # the tag only: no account id in the repo
  run=(docker run --rm -i --platform linux/arm64 --network none
       -v "$root/requirements.txt:/tmp/requirements.txt:ro" --entrypoint python "$image"
       - /tmp/requirements.txt)
else
  source="fresh resolve on $BASE_IMAGE"
  run=(docker run --rm -i --platform linux/arm64
       -v "$root/requirements.txt:/tmp/requirements.txt:ro" --entrypoint sh "$BASE_IMAGE"
       -c 'pip install -q --disable-pip-version-check --root-user-action=ignore \
             -r /tmp/requirements.txt </dev/null >&2 && python - /tmp/requirements.txt')
fi

pins="$(printf '%s\n' "$CLOSURE" | "${run[@]}")"
{
  echo "# Generated by infra/scripts/lock_requirements.sh ($source)."
  echo "# Do not edit by hand: change requirements.txt, then rerun the script."
  printf '%s\n' "$pins"
} > requirements.lock
echo "wrote requirements.lock ($(printf '%s\n' "$pins" | wc -l | tr -d ' ') packages)" >&2
